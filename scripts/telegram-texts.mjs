// Copies the "telegram" texts of src/i18n/messages/{sk,hu,en}.json into the TEXTS block of
// supabase/functions/telegram/index.ts (the function is one file, so it carries its own copy).
// Run: node scripts/telegram-texts.mjs   ·   check only: node scripts/telegram-texts.mjs --check
import { readFileSync, writeFileSync } from "node:fs";

const START = "// ---------------------------------------------------------------- texts (generated by scripts/telegram-texts.mjs from src/i18n/messages — edit there)";
const END = "// ---------------------------------------------------------------- end of the texts";
const FILE = new URL("../supabase/functions/telegram/index.ts", import.meta.url);

const texts = {};
for (const lang of ["sk", "hu", "en"]) {
  const all = JSON.parse(readFileSync(new URL(`../src/i18n/messages/${lang}.json`, import.meta.url), "utf8"));
  texts[lang] = all.telegram ?? {};
}
// Non-ASCII written as \u escapes: the owner may paste the file into the Supabase editor.
const json = JSON.stringify(texts, null, 0).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
const block = `${START}\nexport const TEXTS: Record<Lang, Record<string, string>> = ${json};\n${END}`;

const source = readFileSync(FILE, "utf8");
const a = source.indexOf(START);
const b = source.indexOf(END);
if (a < 0 || b < a) throw new Error("telegram texts markers not found");
const next = source.slice(0, a) + block + source.slice(b + END.length);
if (process.argv.includes("--check")) {
  if (next !== source) {
    console.error("supabase/functions/telegram/index.ts: texts differ from the message files — run node scripts/telegram-texts.mjs");
    process.exit(1);
  }
  console.log("telegram texts in step");
} else {
  writeFileSync(FILE, next);
  console.log("telegram texts written");
}
