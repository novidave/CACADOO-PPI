// The owner's AI assistant engine is ONE file, src/lib/ownerAssistantCore.ts, for the website and the Telegram bot.
// This script (1) writes the help topics of docs/help/*.md into it and (2) copies it unchanged into the Telegram
// function (supabase/functions/telegram/index.ts stays one paste-deployable file).
// Run: node scripts/assistant-core.mjs   ·   check only (npm run test:telegram): node scripts/assistant-core.mjs --check
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const corePath = join(root, "src/lib/ownerAssistantCore.ts");
const fnPath = join(root, "supabase/functions/telegram/index.ts");
const helpDir = join(root, "docs/help");
const HELP_START = "// help topics (generated by scripts/assistant-core.mjs from docs/help — edit there)\n";
const HELP_END = "// end of the help topics\n";
const FN_START = "// ================================================================ owner assistant core (copied from src/lib/ownerAssistantCore.ts by scripts/assistant-core.mjs — edit there)\n";
const FN_END = "// ================================================================ end of the owner assistant core\n";
const check = process.argv.includes("--check");

/** One help file: front matter (title, link, words) + the text. */
function topic(file) {
  const raw = readFileSync(join(helpDir, file), "utf8").replace(/\r\n/g, "\n");
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  if (!m) throw new Error(`docs/help/${file}: no front matter`);
  const meta = Object.fromEntries(m[1].split("\n").map((l) => [l.slice(0, l.indexOf(":")).trim(), l.slice(l.indexOf(":") + 1).trim()]));
  if (!meta.title || !meta.link?.startsWith("/")) throw new Error(`docs/help/${file}: title and link (/…) are needed`);
  return { id: file.replace(/\.md$/, ""), title: meta.title, link: meta.link, words: meta.words ?? "", text: m[2].trim().replace(/\s*\n\s*/g, " ") };
}

const topics = readdirSync(helpDir).filter((f) => f.endsWith(".md") && f !== "README.md").sort().map(topic);
const helpBlock = `${HELP_START}export const HELP: HelpTopic[] = [\n${topics.map((t) => `  ${JSON.stringify(t)},`).join("\n")}\n];\n${HELP_END}`;

const core = readFileSync(corePath, "utf8");
const hs = core.indexOf(HELP_START);
const he = core.indexOf(HELP_END);
if (hs < 0 || he < hs) throw new Error("src/lib/ownerAssistantCore.ts: the help topics' markers are missing");
const nextCore = core.slice(0, hs) + helpBlock + core.slice(he + HELP_END.length);

const fn = readFileSync(fnPath, "utf8");
const fs = fn.indexOf(FN_START);
const fe = fn.indexOf(FN_END);
if (fs < 0 || fe < fs) throw new Error("supabase/functions/telegram/index.ts: the owner assistant core's markers are missing");
const nextFn = fn.slice(0, fs) + FN_START + nextCore + FN_END + fn.slice(fe + FN_END.length);

if (check) {
  let bad = false;
  if (nextCore !== core) {
    console.error("src/lib/ownerAssistantCore.ts: the help topics differ from docs/help — run node scripts/assistant-core.mjs");
    bad = true;
  }
  if (nextFn !== fn) {
    console.error("supabase/functions/telegram/index.ts: the owner assistant core differs from src/lib/ownerAssistantCore.ts — run node scripts/assistant-core.mjs");
    bad = true;
  }
  if (bad) process.exit(1);
  console.log(`owner assistant core: ${topics.length} help topics, the Telegram copy is the same`);
} else {
  if (nextCore !== core) writeFileSync(corePath, nextCore);
  if (nextFn !== fn) writeFileSync(fnPath, nextFn);
  console.log(`owner assistant core: ${topics.length} help topics written, copied into the Telegram function`);
}
